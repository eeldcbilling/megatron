"""Rebuild the chat logs and the prompt index from the pieces in 07-logs/raw.

Each piece is named NNN-prompt.md or NNN-reply.md and starts with a header line:
    <!-- session: 2026-11-13-session-01 | time: 2026-11-13 11:26 IST -->

Run from the repo root:
    python tools/build_logs.py
"""
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "07-logs" / "raw"
CHATS = ROOT / "07-logs" / "chats"
HEADER = re.compile(r"<!--\s*session:\s*(\S+)\s*\|\s*time:\s*(.+?)\s*-->")


def read_piece(path):
    first, _, body = path.read_text(encoding="utf-8").partition("\n")
    match = HEADER.match(first.strip())
    if not match:
        raise SystemExit(f"{path.name}: first line must be the session/time header")
    number, role = path.stem.split("-", 1)
    return {
        "number": number,
        "role": role,
        "session": match.group(1),
        "time": match.group(2),
        "body": body.strip(),
    }


def quote(text):
    return "\n".join("> " + line if line else ">" for line in text.splitlines())


def main():
    pieces = [read_piece(p) for p in sorted(RAW.glob("[0-9][0-9][0-9]-*.md"))]
    sessions = defaultdict(list)
    for piece in pieces:
        sessions[piece["session"]].append(piece)

    CHATS.mkdir(parents=True, exist_ok=True)
    for session, items in sessions.items():
        out = [f"# Chat log: {session}", "", "Generated by `tools/build_logs.py`. Edit the pieces in `07-logs/raw/`, not this file.", ""]
        for item in items:
            who = "Learner" if item["role"] == "prompt" else "Mentor"
            out += [f"## {item['number']} · {who} · {item['time']}", "", item["body"], "", "---", ""]
        (CHATS / f"{session}.md").write_text("\n".join(out), encoding="utf-8")

    prompts = ["# Prompts", "", "Every prompt from the learner, word for word, oldest first. Personal and confidential details are masked as `***` because this repo is public. Generated by `tools/build_logs.py`.", ""]
    for piece in pieces:
        if piece["role"] == "prompt":
            prompts += [
                f"## P{piece['number']} · {piece['time']}",
                "",
                f"Session: [{piece['session']}](chats/{piece['session']}.md)",
                "",
                quote(piece["body"]),
                "",
            ]
    (ROOT / "07-logs" / "prompts.md").write_text("\n".join(prompts), encoding="utf-8")

    index = ["# Logs", "", "| Session | Pieces |", "|---|---|"]
    for session, items in sessions.items():
        index.append(f"| [{session}](chats/{session}.md) | {len(items)} |")
    index += ["", "All prompts in one place: [prompts.md](prompts.md).", "", "To add to the log: save new pieces in `raw/` and run `python tools/build_logs.py`."]
    (ROOT / "07-logs" / "README.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    print(f"{len(pieces)} pieces, {len(sessions)} session(s) written")


if __name__ == "__main__":
    main()
